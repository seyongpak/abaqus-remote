#!/usr/bin/env bash
# Install abaqus-remote:
#   - abq_server.py into %USERPROFILE%\.abq_remote (or $ABQ_REMOTE), with inbox/outbox
#   - the `abq` command into ~/.local/bin
#   - the /abq skill for every AI coding CLI found (Claude Code, Codex, Gemini CLI)
#   - Windows: abq.cmd / Git Bash abq on the user PATH, and skill copies for Windows-native agents
# usage: ./install.sh [--no-agents] [--no-windows]
set -e
cd "$(dirname "$(readlink -f "$0")")"
REPO=$(pwd)
command -v powershell.exe >/dev/null || { echo "powershell.exe not found - this tool needs WSL on Windows"; exit 1; }
if [ -z "$ABQ_REMOTE" ]; then
  win_home=$(cmd.exe /c 'echo %USERPROFILE%' 2>/dev/null | tr -d '\r')
  ABQ_REMOTE="$(wslpath "$win_home")/.abq_remote"
fi
mkdir -p "$ABQ_REMOTE/inbox" "$ABQ_REMOTE/outbox"
cp server/abq_server.py "$ABQ_REMOTE/abq_server.py"
chmod +x abq.sh
echo "Server:  $(wslpath -w "$ABQ_REMOTE")\\abq_server.py"

# `abq` command on PATH (a link, so `git pull` updates it)
mkdir -p "$HOME/.local/bin"
ln -sf "$REPO/abq.sh" "$HOME/.local/bin/abq"
echo "Command: ~/.local/bin/abq -> $REPO/abq.sh"
case ":$PATH:" in *":$HOME/.local/bin:"*) ;; *)
  echo "         (add to ~/.bashrc:  export PATH=\$HOME/.local/bin:\$PATH)";; esac

# AI agent integrations: install for each CLI that is present
if [ "${1:-}" != --no-agents ]; then
  link_skill() {  # $1 = skills dir, $2 = label
    mkdir -p "$1"
    rm -rf "$1/abq"
    ln -s "$REPO/skill/abq" "$1/abq"
    echo "Agent:   $2 -> $1/abq"
  }
  if [ -d "$HOME/.claude" ] || command -v claude >/dev/null; then
    link_skill "$HOME/.claude/skills" "Claude Code  (type /abq)"
  fi
  if [ -d "${CODEX_HOME:-$HOME/.codex}" ] || command -v codex >/dev/null; then
    link_skill "${CODEX_HOME:-$HOME/.codex}/skills" "Codex        (type \$abq)"
  fi
  if [ -d "$HOME/.gemini" ] || command -v gemini >/dev/null; then
    gemini_wsl=1
  fi
  if [ -n "$gemini_wsl" ]; then
    mkdir -p "$HOME/.gemini/commands"
    rm -f "$HOME/.gemini/commands/abq.toml"
    cat > "$HOME/.gemini/commands/abq.toml" <<TOML
description = "Connect to / drive the running Abaqus/CAE session (abaqus-remote)"
prompt = """
Read and follow the instructions in $REPO/skill/abq/SKILL.md.
User request (empty means: just check the connection): {{args}}
"""
TOML
    echo "Agent:   Gemini CLI   (type /abq) -> ~/.gemini/commands/abq.toml"
  fi
fi

# ---- Windows side: abq for PowerShell/cmd/Git Bash, and skills for Windows-native agents
# (VS Code opened on Windows, Claude desktop app Code tab, Codex/Gemini on Windows)
if [ "${1:-}" != --no-windows ] && [ "${2:-}" != --no-windows ]; then
  WIN_HOME=$(cd /mnt/c 2>/dev/null; cmd.exe /c 'echo %USERPROFILE%' 2>/dev/null | tr -d '\r')
  WH=$(wslpath "$WIN_HOME")
  WBIN="$WH/.abq_remote/bin"
  mkdir -p "$WBIN"
  DISTRO=${WSL_DISTRO_NAME:-Ubuntu}
  # cmd / PowerShell wrapper (CRLF line endings)
  sed 's/$/\r/' > "$WBIN/abq.cmd" <<CMD
@echo off
rem abaqus-remote: run abq inside WSL ($DISTRO). Generated by install.sh
setlocal
set "A=%~1"
if "%A%"=="" goto run
if /i "%A%"=="ping" goto run
set "A=%~f1"
:run
wsl.exe -d $DISTRO -- "$REPO/abq.sh" "%A%" %2
exit /b %ERRORLEVEL%
CMD
  # Git Bash wrapper (Claude Code on Windows runs commands in Git Bash)
  cat > "$WBIN/abq" <<SH
#!/usr/bin/env bash
# abaqus-remote: run abq inside WSL ($DISTRO). Generated by install.sh
a="\$1"
if [ -n "\$a" ] && [ "\$a" != ping ]; then a=\$(cygpath -wa "\$a"); fi
MSYS_NO_PATHCONV=1 exec wsl.exe -d $DISTRO -- "$REPO/abq.sh" "\$a" \${2:+"\$2"}
SH
  echo "Windows: $WIN_HOME\\.abq_remote\\bin\\abq.cmd (PowerShell/cmd) and abq (Git Bash)"
  # add the folder to the user PATH once (takes effect in newly opened programs)
  powershell.exe -NoProfile -Command "
    \$d = Join-Path \$env:USERPROFILE '.abq_remote\\bin'
    \$p = [Environment]::GetEnvironmentVariable('Path','User')
    if ((\$p -split ';') -notcontains \$d) {
      [Environment]::SetEnvironmentVariable('Path', ((\$p.TrimEnd(';')) + ';' + \$d), 'User')
      'Windows: added ' + \$d + ' to your user PATH (restart VS Code / the app to pick it up)'
    }" 2>/dev/null | tr -d '\r'
  # skills are copied (Windows programs cannot follow WSL symlinks): re-run install.sh after git pull
  copy_skill() { rm -rf "$1/abq"; mkdir -p "$1"; cp -r "$REPO/skill/abq" "$1/abq"; echo "Windows: $2 -> $(wslpath -w "$1")\\abq"; }
  copy_skill "$WH/.abq_remote/skill" "skill copy"
  if [ "${1:-}" != --no-agents ]; then
    [ -d "$WH/.claude" ] && copy_skill "$WH/.claude/skills" "Claude Code / desktop app (type /abq)"
    [ -d "$WH/.codex" ]  && copy_skill "$WH/.codex/skills"  "Codex (type \$abq)"
    if [ -d "$WH/.gemini" ]; then
      mkdir -p "$WH/.gemini/commands"
      sed 's/$/\r/' > "$WH/.gemini/commands/abq.toml" <<TOML
description = "Connect to / drive the running Abaqus/CAE session (abaqus-remote)"
prompt = """
Read and follow the instructions in $(wslpath -w "$WH/.abq_remote/skill/abq/SKILL.md" | sed 's/\\/\\\\/g').
User request (empty means: just check the connection): {{args}}
"""
TOML
      echo "Windows: Gemini CLI (type /abq) -> $WIN_HOME\\.gemini\\commands\\abq.toml"
    fi
  fi
fi

echo
echo "Next:"
echo "  1. In Abaqus/CAE: File > Run Script...  ->  $(wslpath -w "$ABQ_REMOTE")\\abq_server.py"
echo "  2. Click the >>> command line at the bottom of CAE."
echo "  3. Test:  abq ping        (or type /abq in your AI CLI)"
